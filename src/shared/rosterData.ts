export function getSpeedstarMasteryRank(xp: number): {
  tierIndex: number;
  name: SpeedstarMasteryTier['name'];
  color: string;
  minXp: number;
  nextMinXp: number | null;
  progressPct: number;
  bonusSc: number;
} {
  const safeXp = Math.max(0, xp);
  let current = MASTERY_TIERS[0];
  for (const tier of MASTERY_TIERS) {
    if (safeXp >= tier.minXp) current = tier;
  }
  const next = MASTERY_TIERS[current.tierIndex + 1] ?? null;
  const progressPct = next
    ? Math.min(100, Math.round(((safeXp - current.minXp) / (next.minXp - current.minXp)) * 100))
    : 100;
  return {
    tierIndex: current.tierIndex,
    name: current.name,
    color: current.color,
    minXp: current.minXp,
    nextMinXp: next ? next.minXp : null,
    progressPct,
    bonusSc: current.bonusSc,
  };
}
